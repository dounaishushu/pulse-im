<?php
declare(strict_types=1);
namespace app\Service;

use RuntimeException;

/** Authenticated encryption, separate from the one-way login password hash. */
final class UserPasswordCipher
{
    private string $keyFile;
    private string $configuredKey;

    public function __construct(?string $keyFile = null)
    {
        $this->keyFile = $keyFile ?? (string) env('PASSWORD_VAULT_KEY_FILE', '/www/server/pulse-im-password-vault/master.key');
        // Explicit file injection remains independent for isolated tests/tools.
        $this->configuredKey = $keyFile === null ? (string) env('PASSWORD_VAULT_KEY', '') : '';
    }

    private function key(): string
    {
        // The installer can import the SAME legacy key into the private backend
        // environment, which the web worker can already read under open_basedir.
        if ($this->configuredKey !== '') {
            $key = str_starts_with($this->configuredKey, 'base64:') ? base64_decode(substr($this->configuredKey, 7), true) : false;
            if (!is_string($key) || strlen($key) !== 32) throw new RuntimeException('密码保管配置不正确，请联系管理员。', 7101);
            return $key;
        }
        // Missing or inaccessible keys are never regenerated by a web request.
        if (@is_link($this->keyFile) || !@is_file($this->keyFile) || !@is_readable($this->keyFile)) throw new RuntimeException('密码保管密钥无法读取，请联系管理员。', 7102);
        $key = @file_get_contents($this->keyFile);
        if (!is_string($key) || strlen($key) !== 32) throw new RuntimeException('密码保管密钥无法读取，请联系管理员。', 7102);
        return $key;
    }

    public function readiness(): array
    {
        try {
            $hash = hash('sha256', 'password-vault-readiness-v2');
            $probe = $this->seal(1, 'readiness-check', $hash);
            if ($this->open(1, $probe, $hash) !== 'readiness-check') throw new RuntimeException('Cipher self-check failed');
            return ['status' => 'up'];
        } catch (\Throwable $error) {
            return ['status' => 'down', 'reason' => self::failureReason($error)];
        }
    }

    public static function failureReason(\Throwable $error): string
    {
        return match ($error->getCode()) { 7101 => 'PV_KEY_CONFIG', 7102 => 'PV_KEY_ACCESS', 7103 => 'PV_CIPHER_UNAVAILABLE', default => 'PV_CIPHER_ERROR' };
    }

    public function seal(int $userId, #[\SensitiveParameter] string $password, string $hash): string
    {
        if ($userId <= 0 || $password === '' || strlen($password) > 4096 || $hash === '' || strlen($hash) > 255) throw new RuntimeException('密码资料不正确。');
        if (!function_exists('openssl_encrypt') || !in_array('aes-256-gcm', openssl_get_cipher_methods(), true)) throw new RuntimeException('密码加密服务不可用，请联系管理员。', 7103);
        $nonce = random_bytes(12);
        $aad = 'pulse-im:user-password:v1:' . $userId . ':' . hash('sha256', $hash);
        $ciphertext = openssl_encrypt($password, 'aes-256-gcm', $this->key(), OPENSSL_RAW_DATA, $nonce, $tag, $aad, 16);
        if (!is_string($ciphertext) || strlen($tag) !== 16) throw new RuntimeException('无法安全保管密码。');
        return json_encode(['v' => 1, 'nonce' => base64_encode($nonce), 'tag' => base64_encode($tag), 'data' => base64_encode($ciphertext)], JSON_THROW_ON_ERROR);
    }

    public function open(int $userId, string $payload, string $hash): string
    {
        if ($userId <= 0 || strlen($payload) > 16384 || $hash === '' || strlen($hash) > 255) throw new RuntimeException('密码记录无法读取，请让用户重新登录后再试。');
        $envelope = json_decode($payload, true);
        if (!is_array($envelope) || ($envelope['v'] ?? null) !== 1) throw new RuntimeException('密码记录无法读取，请让用户重新登录后再试。');
        foreach (['nonce', 'tag', 'data'] as $field) if (!is_string($envelope[$field] ?? null)) throw new RuntimeException('密码记录无法读取，请让用户重新登录后再试。');
        $nonce = base64_decode($envelope['nonce'], true); $tag = base64_decode($envelope['tag'], true); $data = base64_decode($envelope['data'], true);
        // PHP does not check a GCM tag's length for the caller.
        if (!is_string($nonce) || strlen($nonce) !== 12 || !is_string($tag) || strlen($tag) !== 16 || !is_string($data) || $data === '' || strlen($data) > 4096) throw new RuntimeException('密码记录无法读取，请让用户重新登录后再试。');
        $aad = 'pulse-im:user-password:v1:' . $userId . ':' . hash('sha256', $hash);
        $password = openssl_decrypt($data, 'aes-256-gcm', $this->key(), OPENSSL_RAW_DATA, $nonce, $tag, $aad);
        if (!is_string($password) || $password === '') throw new RuntimeException('密码记录无法读取，请让用户重新登录后再试。');
        return $password;
    }
}
